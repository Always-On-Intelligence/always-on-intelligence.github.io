"""Export HALO read mode (Section 7.1) into site/data/halo-read.json.

Source in the paper: sec/table_channel_audit.tex, generated by
analysis/evidence/build_channel_inventory_v3.py. Each row gives the five coupling
channels beyond S→A (● reported, ○ explicitly absent, ◐ unreported or insufficiently
specified) and the five steps of the chain of evidence for self-evolution (stated or
not stated).

    python3 tools/paper/export_halo.py [--check]
"""
import json
import re
import sys

from paper_common import PAPER, SITE, cite_keys, clean, labels, prose, ref, split_cells

OUT = SITE / 'site/data/halo-read.json'
COLUMNS = ['S→M', 'M→A', 'A→S', 'M→S', 'A→M']
CHAIN = [
    {'id': 'record', 'short': 'Rec.', 'name': 'Record'},
    {'id': 'outcome', 'short': 'Out.', 'name': 'Outcome'},
    {'id': 'attribution', 'short': 'Attr.', 'name': 'Attribution'},
    {'id': 'revision', 'short': 'Rev.', 'name': 'Revision'},
    {'id': 'later_use', 'short': 'Use.', 'name': 'Later use'},
]
CELL = {'\\HaloReported{}': '●', '\\HaloAbsent{}': '○', '\\HaloPartial{}': '◐'}
STEP = {'\\HaloStep{}': True, '\\HaloNoStep{}': False}


def mark(table, value, row_id):
    if value not in table:
        raise ValueError(f'{row_id}: unknown mark {value!r} in the read-mode table')
    return table[value]


def build():
    text = (PAPER / 'sec/table_channel_audit.tex').read_text()
    caption = re.search(r'\\caption\{(.*?)\}\\label', text, re.S).group(1)
    note = re.search(r'\\TableNote\{(.*)\}\n\\end\{table\}', text, re.S).group(1)
    rows, group, row_id = [], None, None
    for line in text.splitlines():
        band = re.match(r'\\TableSectionColor\{[^}]*\}\{\d+\}\{(\w+)\}', line)
        if band:
            group = band.group(1)
            continue
        if line.startswith('% '):
            row_id = line[2:].strip()
            continue
        if group is None or '\\citep' not in line or not line.rstrip().endswith('\\\\'):
            continue
        cells = split_cells(line.rstrip()[:-2])
        assert len(cells) == 13, (row_id, len(cells))
        label = cells[0]
        keys = cite_keys(label)
        name = clean(re.sub(r'\\citep\{[^}]*\}', '', label).replace('\\textsuperscript{\\dag}', ''))
        links = {}
        for cell, kind in ((cells[11], 'report'), (cells[12], 'code')):
            m = re.search(r'Link\{([^}]*)\}', cell)
            if m:
                links[kind] = m.group(1)
        rows.append({
            'id': row_id,
            'name': name,
            'key': keys[0],
            **({'keys': keys} if len(keys) > 1 else {}),
            'group': group,
            'product': '\\dag' in label,
            'cells': {c: mark(CELL, v, row_id) for c, v in zip(COLUMNS, cells[1:6])},
            'chain': {s['id']: mark(STEP, v, row_id) for s, v in zip(CHAIN, cells[6:11])},
            'links': links,
            'ref': ref(keys[0]),
        })
    # Counts per work, as the paper counts them: a work with several rows (as VisualClaw had
    # for its two backends) counts once, and counts as reported when any of its rows reports.
    works = {}
    for r in rows:
        works.setdefault(r['key'], []).append(r)
    counts = {
        'works': len(works),
        'rows': len(rows),
        'reported': {c: sum(any(r['cells'][c] == '●' for r in rs) for rs in works.values()) for c in COLUMNS},
        'stated': {s['id']: sum(any(r['chain'][s['id']] for r in rs) for rs in works.values()) for s in CHAIN},
    }
    for macro, symbol in (*CELL.items(), ('\\HaloStep{}', '■'), ('\\HaloNoStep{}', '·')):
        caption = caption.replace(macro, symbol)
    return {
        'source': f"Paper §{labels()['sec:halo:results']}, Table {labels()['tab:channel-evidence']}",
        'caption': prose(caption),
        'columns': COLUMNS,
        'chain': CHAIN,
        'notes': [prose(note)],
        'counts': counts,
        'rows': rows,
    }


def main():
    data = build()
    # The paper's prose quotes these counts (Section 7.1); stop if the table and the text disagree.
    halo = (PAPER / 'sec/08_halo.tex').read_text()
    c = data['counts']
    # M→S per work for the works that do not report it: ○ when a row marks it absent, else ◐.
    ms = {}
    for r in data['rows']:
        ms.setdefault(r['key'], set()).add(r['cells']['M→S'])
    ms_absent = sum('●' not in marks and '○' in marks for marks in ms.values())
    ms_partial = sum(marks == {'◐'} for marks in ms.values())
    expected = [f"read mode to {c['works']} works",
                f"\\chSM{{}} and \\chMA{{}} each have {c['reported']['S→M']} reported implementations",
                f"\\chAS{{}} has {c['reported']['A→S']}, and \\chMS{{}} has {c['reported']['M→S']}",
                f"of the remaining {c['works'] - c['reported']['M→S']} works, {ms_partial} provide insufficient detail "
                f"and only {ms_absent} explicitly lack{'s' if ms_absent == 1 else ''} the flow",
                f"{c['reported']['A→M']} report the \\chAM{{}} channel",
                f"which count all {c['works']} works, {c['stated']['record']} keep action records, {c['stated']['outcome']} "
                f"retain outcomes, and {c['stated']['attribution']} link outcomes",
                f"only {c['stated']['revision']} revise their mechanism and only {c['stated']['later_use']} show"]
    missing = [e for e in expected if e not in halo]
    assert c['reported']['S→M'] == c['reported']['M→A'], c
    if missing:
        print('warning: the Section 7.1 counts differ from the table:', missing)
    out = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    if '--check' in sys.argv:
        sys.exit(0 if OUT.read_text() == out else 1)
    OUT.write_text(out)
    print(c)


if __name__ == '__main__':
    main()
